    // (`crates/catcloud-core/src/sync/crypto.rs::tests::golden_vectors_ccsync01_and_tamper_rejection`).
    private val rustGoldenV1EmptySidHex =
        "434353594e43303101000000000000000000000000000000000000000000a0a1a2a3a4a5a6a7a8a9aaab8579084e29a477db4f16febd6457a7b11cc83c7ebfc173504692aa58f0476339af48a31fe3f7df"
    private val rustGoldenV2DemoSidHex =
        "434353594e4330310100000000000000000000000000000000000000001030313233343536373839616263646566a0a1a2a3a4a5a6a7a8a9aaab8579084e29a477db4f16febd6457a7b11cc83c7ebfc173671ba7f8579cf7353a08b9e025e99f60"
    private val rustGoldenV3Pbkdf2Hex =
        "434353594e43303102000003e81111111111111111111111111111111100a0a1a2a3a4a5a6a7a8a9aaab4602075d4fee3bedf9b165ea4576043982fcf5d6f22213e1da98893783bbdab7465420b7169269"

    private fun testKey(): ByteArray = ByteArray(32) { it.toByte() }
    private fun testNonce(): ByteArray = ByteArray(12) { (0xA0 + it).toByte() }

    private fun hexToBytes(hex: String): ByteArray {
        val out = ByteArray(hex.length / 2)
        for (i in out.indices) {
            out[i] = hex.substring(i * 2, i * 2 + 2).toInt(16).toByte()
        }
        return out
    }

    @Test
    fun ccsync01CrossPlatformGoldenVectorsMatchRustBitForBit() {
        val key = testKey()
        val nonce = testNonce()
        val plaintext = "catcloud-sync-golden-v1".toByteArray(Charsets.UTF_8)

        // Vector 1: mode=0x01, empty sid
        val v1 = SyncCrypto.sealWithRawKey(plaintext, key, sid = "", customNonce = nonce)
        assertEquals(rustGoldenV1EmptySidHex, NodeFingerprint.toHexLower(v1))
        assertArrayEquals(plaintext, SyncCrypto.openWithRawKey(hexToBytes(rustGoldenV1EmptySidHex), key, expectedSid = ""))

        // Vector 2: mode=0x01, sid="0123456789abcdef"
        val sid = "0123456789abcdef"
        val v2 = SyncCrypto.sealWithRawKey(plaintext, key, sid = sid, customNonce = nonce)
        assertEquals(rustGoldenV2DemoSidHex, NodeFingerprint.toHexLower(v2))
        assertArrayEquals(plaintext, SyncCrypto.openWithRawKey(hexToBytes(rustGoldenV2DemoSidHex), key, expectedSid = sid))
        assertThrowsAny {
            SyncCrypto.openWithRawKey(v2, key, expectedSid = "fedcba9876543210")
        }

        // Vector 3: mode=0x02, PBKDF2-HMAC-SHA256 iters=1000, salt=0x11*16, pin="123456"
        val salt = ByteArray(16) { 0x11.toByte() }
        val v3 = SyncCrypto.sealWithPassword(plaintext, "123456", sid = "", iters = 1000, customSalt = salt, customNonce = nonce)
        assertEquals(rustGoldenV3Pbkdf2Hex, NodeFingerprint.toHexLower(v3))
        assertArrayEquals(plaintext, SyncCrypto.openWithPassword(hexToBytes(rustGoldenV3Pbkdf2Hex), "123456", expectedSid = ""))
        assertThrowsAny {
            SyncCrypto.openWithPassword(v3, "123457")
        }
    }

    @Test
    fun ccsync01RejectsAnySingleBitTamperAcrossHeaderSidNonceCiphertextAndTag() {
        val key = testKey()
        val nonce = testNonce()
        val plaintext = "catcloud-integrity-check".toByteArray(Charsets.UTF_8)
        val env = SyncCrypto.sealWithRawKey(plaintext, key, sid = "0123456789abcdef", customNonce = nonce)

        val probeIndices = listOf(0, 8, 29, 34, 46, 58, env.lastIndex)
        for (idx in probeIndices) {
            val tampered = env.copyOf()
            tampered[idx] = (tampered[idx].toInt() xor 0x01).toByte()
            assertThrowsAny("Expected failure when flipping bit at index $idx") {
                SyncCrypto.openWithRawKey(tampered, key)
            }
        }
    }

    @Test
    fun ecdhSecp256r1AndHkdfSha256DeriveIdenticalSessionKeyBothSides() {
        val serverKp = SyncCrypto.generateEcdhP256KeyPair()
        val clientKp = SyncCrypto.generateEcdhP256KeyPair()

        val serverPubSec1 = SyncCrypto.encodeP256PublicKeySec1(serverKp.public)
        val clientPubSec1 = SyncCrypto.encodeP256PublicKeySec1(clientKp.public)
        assertEquals(65, serverPubSec1.size)
        assertEquals(0x04.toByte(), serverPubSec1[0])
        assertEquals(65, clientPubSec1.size)
        assertEquals(0x04.toByte(), clientPubSec1[0])

        val decodedServerPub = SyncCrypto.decodeP256PublicKeySec1(serverPubSec1)
        val decodedClientPub = SyncCrypto.decodeP256PublicKeySec1(clientPubSec1)

        val sharedServer = SyncCrypto.computeEcdhSharedSecret(serverKp.private, decodedClientPub)
        val sharedClient = SyncCrypto.computeEcdhSharedSecret(clientKp.private, decodedServerPub)
        assertArrayEquals(sharedServer, sharedClient)

        val challenge = SyncCrypto.randomBytes(16)
        val sid = "0123456789abcdef"
        val keyServer = SyncCrypto.derivePinSessionKey(challenge, sharedServer, sid)
        val keyClient = SyncCrypto.derivePinSessionKey(challenge, sharedClient, sid)
        assertEquals(32, keyServer.size)
        assertArrayEquals(keyServer, keyClient)

        val challengeB64 = Base64.getEncoder().encodeToString(challenge)
        val serverB64 = Base64.getEncoder().encodeToString(serverPubSec1)
        val clientB64 = Base64.getEncoder().encodeToString(clientPubSec1)
        val proof1 = SyncCrypto.computePinProof("482913", sid, challengeB64, serverB64, clientB64)
        val proof2 = SyncCrypto.computePinProof("482914", sid, challengeB64, serverB64, clientB64)
        assertEquals(64, proof1.length)
        assertNotEquals(proof1, proof2)

        val macPost = SyncCrypto.computeAuthMac(keyClient, "POST", "/sync/v1/bundle", sid)
        val macGet = SyncCrypto.computeAuthMac(keyClient, "GET", "/sync/v1/bundle", sid)
        assertEquals(64, macPost.length)
        assertNotEquals(macPost, macGet)
    }

    @Test
    fun syncUriEnforcesFragmentOnlyKeyAndStrictPublicHttpsSsrfGuard() {
        val key = ByteArray(32) { 0x42.toByte() }
        val fp = SyncCrypto.bundleFingerprintHex16("demo-zip".toByteArray())
        assertEquals(16, fp.length)

        val pullUri = SyncCrypto.formatSyncUri(
            role = SyncRole.PULL,
            keyBytes = key,
            sid = "0123456789abcdef",
            hosts = listOf("192.168.1.25", "10.0.0.8"),
            port = 43210,
            customEndpoint = "https://sync.example.com:8443",
            fpHex = fp,
        )
        assertTrue(pullUri.startsWith("catcloud://sync/v1?"))
        assertTrue(pullUri.contains("#k="))
        assertFalse(pullUri.substringBefore('#').contains("k="))

        val parsed = SyncCrypto.parseSyncUri(pullUri)
        assertEquals(SyncRole.PULL, parsed.role)
        assertEquals(listOf("192.168.1.25", "10.0.0.8"), parsed.hosts)
        assertEquals(43210, parsed.port)
        assertEquals("0123456789abcdef", parsed.sid)
        assertEquals(fp, parsed.fpHex)
        assertArrayEquals(key, parsed.keyBytes)

        // Alias scheme compatibility (`catcloud-sync://v1`)
        val alias = pullUri.replaceFirst("catcloud://sync/v1", "catcloud-sync://v1")
        assertArrayEquals(key, SyncCrypto.parseSyncUri(alias).keyBytes)

        // Reject key leaked into ?query
        val kB64 = Base64.getUrlEncoder().withoutPadding().encodeToString(key)
        assertThrowsAny("Must reject k in query string") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=file_key&k=$kB64#k=$kB64")
        }

        // Valid public HTTPS relay_url passes
        val validRelayUri = SyncCrypto.formatSyncUri(
            role = SyncRole.RELAY_URL,
            keyBytes = key,
            relayUrl = "https://relay.example.org/bundles/demo.ccsync",
            fpHex = fp,
        )
        assertEquals(SyncRole.RELAY_URL, SyncCrypto.parseSyncUri(validRelayUri).role)

        // SSRF & cleartext public URLs must all be rejected
        val forbiddenUrls = listOf(
            "http://relay.example.org/demo.ccsync",
            "https://127.0.0.1/demo.ccsync",
            "https://localhost/demo.ccsync",
            "https://192.168.1.1/demo.ccsync",
            "https://10.0.0.1/demo.ccsync",
            "https://172.16.0.5/demo.ccsync",
            "https://169.254.169.254/latest/meta-data/",
            "https://198.18.0.1/demo.ccsync",
            "https://[::1]/demo.ccsync",
            "https://[fc00::1]/demo.ccsync",
            "https://[fe80::1]/demo.ccsync",
            "https://user:pass@relay.example.org/demo.ccsync",
        )
        for (bad in forbiddenUrls) {
            assertThrowsAny("Must reject SSRF/non-HTTPS relay_url: $bad") {
                SyncCrypto.validatePublicHttpsUrl(bad)
            }
        }

        // Public cleartext endpoint must be rejected, while RFC1918 LAN HTTP is allowed
        assertThrowsAny { SyncCrypto.validateLanOrHttpsEndpoint("http://sync.example.org:8080") }
        SyncCrypto.validateLanOrHttpsEndpoint("http://192.168.1.25:43210")
        SyncCrypto.validateLanOrHttpsEndpoint("https://sync.example.org:8443")
    }

    @Test
    fun enforcesStrictProtocolBoundsCaseInsensitiveQueryKeyAndExtendedSpecialIps() {
        val key = ByteArray(32) { 0x55.toByte() }
        val kB64 = Base64.getUrlEncoder().withoutPadding().encodeToString(key)

        // 1. Case-insensitive query key check rejects uppercase K and percent-encoded %4B
        assertThrowsAny("Uppercase K in query must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=file_key&K=$kB64#k=$kB64")
        }
        assertThrowsAny("Percent-encoded %4B in query must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=file_key&%4B=$kB64#k=$kB64")
        }

        // 2. sealWithPassword enforces PBKDF2 iteration bounds [1_000..2_000_000]
        assertThrowsAny("PBKDF2 iterations below 1000 must be rejected") {
            SyncCrypto.sealWithPassword("demo".toByteArray(), "123456", iters = 999)
        }
        assertThrowsAny("PBKDF2 iterations above 2000000 must be rejected") {
            SyncCrypto.sealWithPassword("demo".toByteArray(), "123456", iters = 2_000_001)
        }

        // 3. PULL/PUSH require non-empty <=64B sid, (ep or hosts+port), and valid 16-hex fp when present
        assertThrowsAny("PULL without sid must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=pull&hosts=192.168.1.2&port=43210#k=$kB64")
        }
        assertThrowsAny("PUSH without sid must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=push&hosts=192.168.1.2&port=43210#k=$kB64")
        }
        val oversizedSid = "a".repeat(65)
        assertThrowsAny("PULL with >64B sid must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=pull&sid=$oversizedSid&hosts=192.168.1.2&port=43210#k=$kB64")
        }
        assertThrowsAny("PULL without ep or hosts+port must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=pull&sid=0123456789abcdef#k=$kB64")
        }
        assertThrowsAny("PULL with hosts but missing port and ep must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=pull&sid=0123456789abcdef&hosts=192.168.1.2#k=$kB64")
        }
        assertThrowsAny("Invalid fp length must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=file_key&fp=0123456789abcde#k=$kB64")
        }
        assertThrowsAny("Non-hex fp must be rejected") {
            SyncCrypto.parseSyncUri("catcloud://sync/v1?role=file_key&fp=0123456789abcdeg#k=$kB64")
        }

        // 4. Extended special/reserved IP ranges aligned with Rust (NAT64, IPv4-compat, TEST-NET, RFC 6890, 2001:db8::/32)
        val rfc6890Ip = InetAddress.getByAddress(byteArrayOf(192.toByte(), 0, 0, 1))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(rfc6890Ip))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("192.0.2.1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("198.51.100.1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("203.0.113.1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("2001:db8::1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("64:ff9b::1.1.1.1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("::127.0.0.1")))
        assertTrue(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("::1.1.1.1")))

        assertFalse(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("1.1.1.1")))
        assertFalse(SyncCrypto.isSpecialOrPrivateIp(InetAddress.getByName("8.8.8.8")))

        val extendedForbiddenUrls = listOf(
            "https://${listOf(192, 0, 0, 1).joinToString(".")}/demo.ccsync",
            "https://192.0.2.1/demo.ccsync",
            "https://198.51.100.1/demo.ccsync",
            "https://203.0.113.1/demo.ccsync",
            "https://[2001:db8::1]/demo.ccsync",
            "https://[64:ff9b::1.1.1.1]/demo.ccsync",
            "https://[::127.0.0.1]/demo.ccsync",
            "https://[::1.1.1.1]/demo.ccsync",
        )
        for (bad in extendedForbiddenUrls) {
            assertThrowsAny("Must reject extended reserved IP URL: $bad") {
                SyncCrypto.validatePublicHttpsUrl(bad)
            }
        }
    }

    @Test
    fun zxingQrMatrixRoundtripsSyncUriAccurately() {
        val key = ByteArray(32) { (it + 7).toByte() }
        val uri = SyncCrypto.formatSyncUri(
            role = SyncRole.PULL,
            keyBytes = key,
            sid = "0123456789abcdef",
            hosts = listOf("192.168.31.10"),
            port = 27999,
            fpHex = "0123456789abcdef",
        )
        val matrix = QrBitmapGenerator.encodeQrMatrix(uri, sizePx = 320)
        val decoded = QrBitmapGenerator.decodeFromMatrix(matrix)
        assertEquals(uri, decoded)
    }

